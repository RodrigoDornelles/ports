// xxd: embeds files in C, like xxd -i, as one header on stdout.
//
// usage: xxd <file>...
//
// Each file becomes a byte array named after the file without its
// extension (shaders/vert_wall.glsl -> vert_wall; anything that cannot be
// in a C name becomes '_'), with a 0 byte after the content so text files
// can be used as strings, and <name>_size, the size of the content
// without that 0.

#include <cctype>
#include <cstddef>
#include <filesystem>
#include <format>
#include <fstream>
#include <iostream>
#include <iterator>
#include <set>
#include <stdexcept>
#include <string>
#include <string_view>

namespace fs = std::filesystem;

namespace {

struct Error : std::runtime_error {
    using std::runtime_error::runtime_error;
};

std::string read_file(const fs::path& path)
{
    std::ifstream in{path, std::ios::binary};
    if (!in)
        throw Error{std::format("{}: error: cannot open file", path.string())};
    return {std::istreambuf_iterator<char>{in}, {}};
}

std::string c_name(const fs::path& path)
{
    std::string name = path.stem().string();
    for (char& c : name)
        if (!std::isalnum(static_cast<unsigned char>(c)))
            c = '_';
    if (name.empty() || std::isdigit(static_cast<unsigned char>(name.front())))
        name.insert(0, "_");
    return name;
}

std::string embed(const fs::path& path, std::string_view name)
{
    const std::string content = read_file(path);
    std::string out = std::format("/* {} */\nstatic const unsigned char {}[] = {{", path.filename().string(), name);
    for (std::size_t i = 0; i <= content.size(); i++) {
        const auto byte = i < content.size() ? static_cast<unsigned char>(content[i]) : 0;
        out += std::format("{}0x{:02x},", i % 12 ? " " : "\n   ", byte);
    }
    out += std::format("\n}};\nstatic const unsigned int {}_size = {};\n\n", name, content.size());
    return out;
}

} // namespace

int main(int argc, char** argv)
{
    try {
        if (argc < 2)
            throw Error{"usage: xxd <file>..."};
        std::set<std::string> names;
        std::string header = "/* generated by dopo/scripts/xxd.cpp, do not edit */\n\n";
        for (int i = 1; i < argc; i++) {
            const fs::path path{argv[i]};
            const std::string name = c_name(path);
            if (!names.insert(name).second)
                throw Error{std::format("{}: error: another file is already named {}", path.string(), name)};
            header += embed(path, name);
        }
        std::cout << header;
        return 0;
    } catch (const std::exception& e) {
        std::cerr << e.what() << '\n';
        return 1;
    }
}
